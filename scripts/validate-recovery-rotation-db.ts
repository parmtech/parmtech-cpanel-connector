import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {Pool} from 'pg';
import {HostedRepository} from '../src/hosted/repository.js';
import {rotateAccountKeys} from '../src/hosted/rotate-key.js';
import {decryptSecret,hashToken} from '../src/hosted/crypto.js';
const base = new Pool({max:1}), schema = 'pcc_security_test_'+randomBytes(8).toString('hex');
let pool:Pool|undefined, created=false;
try {
 await base.query(`CREATE SCHEMA "${schema}"`); created=true;
 pool = new Pool({max:4,options:'-c search_path='+schema});
 const repo = new HostedRepository(pool); await repo.initialize();
 const oldKey=randomBytes(32), newKey=randomBytes(32); process.env.CREDENTIAL_ENCRYPTION_KEY=oldKey.toString('base64');
 const setup=await repo.requestAdminSetup('owner@example.test','setup-browser');
 const user=(await repo.finishAdminSetup(setup.id,setup.code,'setup-browser','first-password-123'))!;
 const session=await repo.createSession(user.id);
 const clientId='test-client';
 await pool.query("INSERT INTO oauth_clients(client_id,client_data) VALUES($1,'{}')",[clientId]);
 await pool.query("INSERT INTO oauth_tokens(token_hash,client_id,user_id,token_type,resource,scopes,expires_at) VALUES($1,$2,$3,'access','https://example.test/mcp',ARRAY['accounts:read'],now()+interval '1 hour')",[hashToken('fixture-token'),clientId,user.id]);
 const account=await repo.addAccount(user.id,{label:'fixture',host:'https://example.test:2083',username:'fixture',kind:'cpanel',authType:'token',apiToken:'test-only-token'});
 const before=(await pool.query('SELECT encrypted_credentials FROM cpanel_accounts WHERE id=$1',[account.id])).rows[0].encrypted_credentials;
 await assert.rejects(rotateAccountKeys(pool,randomBytes(32),newKey));
 assert.equal((await pool.query('SELECT encrypted_credentials FROM cpanel_accounts WHERE id=$1',[account.id])).rows[0].encrypted_credentials,before,'wrong key must roll back');
 assert.equal(await rotateAccountKeys(pool,oldKey,newKey),1);
 const after=(await pool.query('SELECT encrypted_credentials FROM cpanel_accounts WHERE id=$1',[account.id])).rows[0].encrypted_credentials;
 assert.notEqual(after,before); assert.throws(()=>decryptSecret(after,`account:${user.id}:${account.id}`,oldKey));
 process.env.CREDENTIAL_ENCRYPTION_KEY=newKey.toString('base64');
 assert.equal((await repo.getAccount(user.id,account.id)).credentials.apiToken,'test-only-token');
 const unknown=await repo.requestPasswordRecovery('unknown@example.test','recovery-browser'); assert.equal(unknown.code,undefined);
 const challenge=await repo.requestPasswordRecovery(user.email,'recovery-browser'); assert.ok(challenge.code);
 assert.equal(await repo.finishPasswordRecovery(challenge.id,challenge.code,'wrong-browser','replacement-password-456'),false);
 const wrong=challenge.code==='00000000'?'11111111':'00000000';
 assert.equal(await repo.finishPasswordRecovery(challenge.id,wrong,'recovery-browser','replacement-password-456'),false);
 const results=await Promise.all([repo.finishPasswordRecovery(challenge.id,challenge.code,'recovery-browser','replacement-password-456'),repo.finishPasswordRecovery(challenge.id,challenge.code,'recovery-browser','replacement-password-456')]);
 assert.deepEqual(results.sort(),[false,true]);
 assert.equal(await repo.authenticate(user.email,'first-password-123'),null);
 assert.ok(await repo.authenticate(user.email,'replacement-password-456'));
 assert.equal(await repo.getSession(session.cookie),null);
 assert.equal(Number((await pool.query('SELECT count(*) AS n FROM oauth_tokens WHERE user_id=$1',[user.id])).rows[0].n),0);
 assert.equal((await repo.getAccount(user.id,account.id)).credentials.apiToken,'test-only-token');
 const expired=await repo.requestPasswordRecovery(user.email,'recovery-browser'); assert.ok(expired.code);
 await pool.query("UPDATE password_recovery_challenges SET expires_at=now()-interval '1 second' WHERE id=$1",[expired.id]);
 assert.equal(await repo.finishPasswordRecovery(expired.id,expired.code,'recovery-browser','other-password-789'),false);
 const locked=await repo.requestPasswordRecovery(user.email,'recovery-browser'); assert.ok(locked.code);
 const incorrect=locked.code==='00000000'?'11111111':'00000000';
 for(let i=0;i<5;i++) assert.equal(await repo.finishPasswordRecovery(locked.id,incorrect,'recovery-browser','other-password-789'),false);
 assert.equal(await repo.finishPasswordRecovery(locked.id,locked.code,'recovery-browser','other-password-789'),false);
 assert.equal((await repo.requestPasswordRecovery(user.email,'recovery-browser')).code,undefined);
 console.log('Recovery and rotation database tests passed; only isolated fixtures used.');
} finally { if(pool)await pool.end(); if(created)await base.query(`DROP SCHEMA "${schema}" CASCADE`); await base.end(); }
